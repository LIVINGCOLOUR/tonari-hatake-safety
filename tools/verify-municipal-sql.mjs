// Isolated PostgreSQL execution. Geometry serialization is stubbed; no production connection.
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const { PGlite } = await import(process.env.PGLITE_MODULE || '/tmp/hatake-sql-check/node_modules/@electric-sql/pglite/dist/index.js');
const db = new PGlite();
const owner='00000000-0000-0000-0000-000000000001', regular='00000000-0000-0000-0000-000000000002';
const base=await readFile('supabase/migrations/202607240002_rls_and_audit.sql','utf8');
try {
await db.exec(`
create role anon; create role authenticated;
create schema auth; create schema extensions;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
create function extensions.gen_random_uuid() returns uuid language sql as $$ select gen_random_uuid() $$;
create function extensions.st_asgeojson(value jsonb) returns text language sql immutable as $$ select value::text $$;
create table profiles(id uuid primary key,profile_data jsonb);
create table workspaces(id uuid primary key default gen_random_uuid(),slug text unique,name text,prefecture text,municipality text,district text,created_by uuid);
create table workspace_memberships(workspace_id uuid,user_id uuid,role text,status text default 'active',created_by uuid,updated_at timestamptz,primary key(workspace_id,user_id,role));
create table workspace_invites(role text,revoked_at timestamptz);
create table fields(id uuid primary key,workspace_id uuid,owner_user_id uuid,archived_at timestamptz,visibility_level text,geometry jsonb);
create table field_access_grants(field_id uuid,grantee_user_id uuid,expires_at timestamptz);
create table operation_plans(id uuid primary key default gen_random_uuid(),workspace_id uuid,field_id uuid,created_by uuid,archived_at timestamptz,visibility_level text,planned_date date,time_window text,district text,status text,plan_data jsonb);
create table notification_targets(plan_id uuid,recipient_user_id uuid,field_id uuid);
create function create_workspace_with_admin(text,text,text,text) returns uuid language sql as $$ select gen_random_uuid() $$;
grant usage on schema public,auth to authenticated;
grant all on all tables in schema public to authenticated;
insert into auth.users values ('${owner}'),('${regular}');
`);
await db.exec(base.slice(base.indexOf('create or replace function public.is_workspace_member'),base.indexOf('create or replace function public.can_read_field')));
await db.exec(await readFile('supabase/migrations/202609090001_platform_role_grants.sql','utf8'));
await db.query('insert into app_administrators values ($1)',[owner]);
await db.exec(await readFile('supabase/migrations/202609090002_municipal_onboarding.sql','utf8'));
const login=async user=>{await db.query("select set_config('request.jwt.claim.sub',$1,false)",[user]);await db.exec('set role authenticated');};
await login(regular);
const joined=(await db.query("select join_municipality('08201',array['sprayer','neighbor']) as id")).rows[0].id;
assert.equal((await db.query('select count(*)::int as n from workspace_memberships where user_id=$1 and role=\'admin\'',[regular])).rows[0].n,0);
await assert.rejects(db.query("select join_municipality('08201',array['admin'])"),e=>e.code==='42501');
await assert.rejects(db.query("select join_municipality('08205',array['neighbor'])"),e=>e.code==='22023');
await assert.rejects(db.query('select assign_regional_administrator($1,$2,true)',[joined,regular]),e=>e.code==='42501');
await assert.rejects(db.query('insert into app_administrators values ($1)',[regular]),e=>e.code==='42501');
await db.exec('reset role');
const field='00000000-0000-0000-0000-000000000010';
await db.query("insert into fields(id,workspace_id,owner_user_id,visibility_level,geometry) values($1,$2,$3,'workspace',$4)",[field,joined,owner,JSON.stringify({type:'Polygon',coordinates:[]})]);
await db.query("insert into operation_plans(workspace_id,field_id,created_by,visibility_level,planned_date,status,plan_data) values($1,$2,$3,'workspace',current_date,'planned',$4)",[joined,field,owner,JSON.stringify({shareWithRegion:true,contact:'MUST NOT LEAK'})]);
await login(regular);
const rows=(await db.query("select * from municipal_schedule('08201')")).rows;
assert.equal(rows.length,1);
assert.deepEqual(Object.keys(rows[0]).sort(),['id','planned_date','time_window','district','status','geometry'].sort());
assert.ok(!JSON.stringify(rows).includes('MUST NOT LEAK'));
assert.equal((await db.query('select can_read_plan($1) as allowed',[rows[0].id])).rows[0].allowed,false);
assert.equal((await db.query('select can_read_field($1) as allowed',[field])).rows[0].allowed,false);
assert.equal((await db.query("select * from municipal_schedule('08216')")).rows.length,0);
await db.exec('reset role');
await db.query("update fields set visibility_level='private' where id=$1",[field]);
await login(regular);
assert.equal((await db.query("select * from municipal_schedule('08201')")).rows[0].geometry,null);
await db.exec('reset role');
await db.query("update operation_plans set plan_data='{}'");
await login(regular);
assert.equal((await db.query("select * from municipal_schedule('08201')")).rows.length,0);
await db.exec('reset role');
await db.query("update workspace_memberships set status='suspended' where user_id=$1 and role='neighbor'",[regular]);
await login(regular);
await assert.rejects(db.query("select join_municipality('08201',array['neighbor'])"),e=>e.code==='42501');
await db.exec('reset role');
await login(owner);
await db.query("select join_municipality('08216',array['sprayer'])");
assert.equal((await db.query("select count(*)::int as n from workspace_memberships where user_id=$1 and role='admin' and status='active'",[owner])).rows[0].n,1);
console.log('Municipal join, owner-only administration, suspension and safe schedule projection verified.');
} finally { await db.close(); }
